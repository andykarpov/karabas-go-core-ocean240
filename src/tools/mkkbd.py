#!/usr/bin/env python3
"""The keyboard map of the Ocean: PS/2 set 2 scancodes -> src/rtl/ocean/ocean_kbd_map.v (a case table).

  {e0, scancode} -> {valid, ascii (unshifted, shifted: the 240/7 monitor), row 0..10 / column 0..7 (the positional
  keyboard of HARDWARE MONITOR+, the matrix of MAME okean240a X0..X10)}. A US PC layout gives the ASCII.
  The arrows of the 240/7 monitor: 08 left, 18 right, 19 up, 1A down (its screen driver at E7DE-E861 takes them).
  mkkbd.py src/rtl/ocean/ocean_kbd_map.v
"""
import sys

# name: (scancode, e0, ascii, shifted ascii, row, col)  row None: not on the positional keyboard
K = {}
def k(name, sc, a, sa, row=None, col=None, e0=0):
    K[name] = (sc, e0, a, sa, row, col)

letters = {'A': 0x1C, 'B': 0x32, 'C': 0x21, 'D': 0x23, 'E': 0x24, 'F': 0x2B, 'G': 0x34, 'H': 0x33, 'I': 0x43, 'J': 0x3B,
           'K': 0x42, 'L': 0x4B, 'M': 0x3A, 'N': 0x31, 'O': 0x44, 'P': 0x4D, 'Q': 0x15, 'R': 0x2D, 'S': 0x1B, 'T': 0x2C,
           'U': 0x3C, 'V': 0x2A, 'W': 0x1D, 'X': 0x22, 'Y': 0x35, 'Z': 0x1A}
# MAME okean240a: X2 J F Q, X3 C Y, X4 U W S, X5 K A M, X6 E P I, X7 N R T, X8 G O X, X9 L B H, X10 D V Z
pos = {'J': (2, 1), 'F': (2, 2), 'Q': (2, 3), 'C': (3, 2), 'Y': (3, 3), 'U': (4, 2), 'W': (4, 3), 'S': (4, 4),
       'K': (5, 2), 'A': (5, 3), 'M': (5, 4), 'E': (6, 1), 'P': (6, 2), 'I': (6, 3), 'N': (7, 2), 'R': (7, 3),
       'T': (7, 4), 'G': (8, 2), 'O': (8, 3), 'X': (8, 4), 'L': (9, 2), 'B': (9, 3), 'H': (9, 6), 'D': (10, 2),
       'V': (10, 5), 'Z': (10, 6)}
for c, sc in letters.items():
    r, cl = pos[c]
    k(c, sc, ord(c), ord(c.lower()), r, cl)   # the monitor and CP/M work in capitals: Shift gives the small letter
digits = {'1': (0x16, '!', 3, 1), '2': (0x1E, '@', 4, 1), '3': (0x26, '#', 5, 1), '4': (0x25, '$', 6, 0),
          '5': (0x2E, '%', 7, 1), '6': (0x36, '^', 8, 1), '7': (0x3D, '&', 9, 0), '8': (0x3E, '*', 10, 0),
          '9': (0x46, '(', 10, 7), '0': (0x45, ')', 9, 7)}
for d, (sc, s, r, cl) in digits.items():
    k('d' + d, sc, ord(d), ord(s), r, cl)
k('grave', 0x0E, ord('`'), ord('~'), 2, 0)       # "@ `"
k('minus', 0x4E, ord('-'), ord('_'), 8, 7)       # "- ="
k('equals', 0x55, ord('='), ord('+'), 3, 4)      # "^ ~"
k('lbr', 0x54, ord('['), ord('{'), 9, 1)
k('rbr', 0x5B, ord(']'), ord('}'), 10, 1)
k('bslash', 0x5D, ord('\\'), ord('|'), 9, 5)
k('semi', 0x4C, ord(';'), ord(':'), 10, 3)       # "; +"
k('quote', 0x52, ord("'"), ord('"'), 8, 6)       # ": *"
k('comma', 0x41, ord(','), ord('<'), 10, 4)
k('dot', 0x49, ord('.'), ord('>'), 8, 5)
k('slash', 0x4A, ord('/'), ord('?'), 6, 7)
k('space', 0x29, 0x20, 0x20, 6, 4)
k('enter', 0x5A, 0x0D, 0x0D, 6, 6)
k('bs', 0x66, 0x08, 0x08, 5, 5)
k('tab', 0x0D, 0x09, 0x09, 1, 1)
k('esc', 0x76, 0x1B, 0x1B, 1, 0)
k('end', 0x69, 0x5F, 0x5F, 7, 7, e0=1)          # "_" of MAME
k('del', 0x71, 0x7F, 0x7F, e0=1)
k('left', 0x6B, 0x08, 0x08, e0=1)
k('right', 0x74, 0x18, 0x18, e0=1)
k('up', 0x75, 0x19, 0x19, e0=1)
k('down', 0x72, 0x1A, 0x1A, e0=1)
pad = {'7': (0x6C, 0, 5), '8': (0x75, 0, 6), '9': (0x7D, 0, 7), '0': (0x70, 1, 5), '1': (0x69, 2, 5), '2': (0x72, 2, 6),
       '3': (0x7A, 2, 7), '4': (0x6B, 3, 5), '5': (0x73, 3, 6), '6': (0x74, 3, 7)}
for d, (sc, r, cl) in pad.items():
    k('kp' + d, sc, ord(d), ord(d), r, cl)
k('kpdot', 0x71, ord('.'), ord('.'), 1, 6)
k('kpenter', 0x5A, 0x0D, 0x0D, 1, 7, e0=1)

lines = ['// generated by src/tools/mkkbd.py, do not edit',
         '// {e0, scancode} -> {pos (1 = on the positional keyboard), row[3:0], col[2:0], ascii shifted[6:0], ascii[6:0]}',
         '`timescale 1ns / 1ps', 'module ocean_kbd_map (input wire [8:0] code, output reg valid, output reg [6:0] ascii,',
         '\toutput reg [6:0] ascii_sh, output reg pos, output reg [3:0] row, output reg [2:0] col);', 'always @(*) begin',
         "\tvalid = 1'b1; pos = 1'b0; row = 4'd0; col = 3'd0; ascii = 7'd0; ascii_sh = 7'd0;", '\tcase (code)']
seen = set()
for name, (sc, e0, a, sa, r, cl) in K.items():
    key = (e0, sc)
    assert key not in seen, name
    seen.add(key)
    p = f"pos = 1'b1; row = 4'd{r}; col = 3'd{cl}; " if r is not None else ''
    lines.append(f"\t\t9'h{e0 << 8 | sc:03X}: begin {p}ascii = 7'h{a:02X}; ascii_sh = 7'h{sa:02X}; end  // {name}")
lines += ["\t\tdefault: valid = 1'b0;", '\tendcase', 'end', 'endmodule']
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
