#!/usr/bin/env python3
"""The colour PROM DD66 (K556RT4, 256 x 4) -> src/rtl/ocean/ocean_prom_vc.v (a case table, XST makes a ROM / LUTs).
  mkprom.py upstream/ocean-240.2/ROMs/Ocean_240_RT4_VC.bin src/rtl/ocean/ocean_prom_vc.v
"""
import sys

data = open(sys.argv[1], 'rb').read()
assert len(data) == 256
lines = ['// generated by src/tools/mkprom.py from Ocean_240_RT4_VC.bin (romychs/ocean-240.2, = fig. 6 of MPSS 1986/4), do not edit',
         '// DD66: a = {BLNK, C/~M, COL3, COL2, COL1, RG2, RG1, 6M}, d = {R, B, G, BLANC}',
         '`timescale 1ns / 1ps', 'module ocean_prom_vc (input wire [7:0] a, output reg [3:0] d);', 'always @(*) begin', '\tcase (a)']
for i, b in enumerate(data):
    if b & 15:
        lines.append(f"\t\t8'h{i:02X}: d = 4'h{b & 15:X};")
lines += ["\t\tdefault: d = 4'h0;", '\tendcase', 'end', 'endmodule']
open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
