#!/usr/bin/env python3
"""KiCad XML netlist of the Ocean-240.2 replica -> structural Verilog (module schem) for Icarus.

  gen_schem.py NETLIST OUT.v [--report]

Every digital part becomes an instance of a pin-numbered model (ttl.v, lsi.v, the CPU adapter in tb_schem.v).
Nets are tri1 (an undriven TTL input reads 1), GND = 0, VCC = 1. Analog parts (transistors, op-amps, R, C, the crystal)
are left out; the few places where they matter are patched in OVERRIDES below, each with the reason.
"""
import re
import sys
import xml.etree.ElementTree as ET

MODELS = {
    'КР1533ЛА3': 'k1533la3', 'КР1533ЛИ1': 'k1533li1', 'КР1533ЛЛ1': 'k1533ll1', 'КР1533ЛП5': 'k1533lp5',
    'КР1533ЛЕ1': 'k1533le1', 'КР1533ЛН1': 'k1533ln1', 'КР1533ЛН3': 'k1533ln3', 'КР1533ТЛ2': 'k1533tl2',
    'КР1533ТМ2': 'k1533tm2', 'КР1533ИЕ5': 'k1533ie5', 'КР1533ИЕ7': 'k1533ie7', 'КР1533ИР16': 'k1533ir16',
    'КР1533КП12': 'k1533kp12', 'КР1533КП13': 'k1533kp13', 'КР1533КП11A': 'k1533kp11', 'К555ИМ6': 'k555im6',
    'К555СП1': 'k555sp1', 'КР1533ИД4': 'k1533id4', 'К170АП3': 'k170ap3', 'КР565РУ7Г': 'ru7',
    'M27256': 'm27256', 'К556РТ4': 'k556rt4',
    'КР580ВК28': 'vk28', 'КР580ВВ55': 'vv55', 'КР580ВИ53': 'vi53', 'КР580ВН59': 'vn59', 'КР580ВВ51': 'vv51',
    'КР580ВМ80А': 'cpu8080',
}
PARAMS = {'DD1': '.FILE(ROM0)', 'DD2': '.FILE(ROM1)', 'DD66': '.FILE(PROM_VC)'}
DRIVER_TYPES = {'output', 'tri_state', 'bidirectional', 'open_collector', 'open_emitter'}

# (ref, pin) left unconnected: the crystal oscillator inverters of DD8 (the testbench drives OSC instead)
CUT = {('DD8', '6'), ('DD8', '8')}
# extra continuous assignments: net <- expression of nets / testbench ports
OVERRIDES = [
    # crystal: one inverter output of the oscillator, also the clock of DD13.2 (F2 flip-flop)
    ('Net-(DD13.2-С)', 'osc'),
    # DD7 inputs are AC-coupled (C2 / C3) to ~F1 / ~F2
    ('Net-(DD7-I1)', '~{F1}'),
    ('Net-(DD7-I2)', '~{F2}'),
    # RC reset (C1 / R1, the reset button) into the Schmitt trigger DD12.1, and RS-232 in through MAX232
    ('RST_BTN', 'rst_btn'),
    ('RXD', 'rxd'),
]
# short names for the testbench: pr_<key> = net
PROBES = {
    'HS': 'HS', 'VS': 'VS', 'GC': 'GC', 'GK': 'GK', 'SYNC': 'SYNC', 'F1': 'CPU_F1', 'F2CPU': 'CPU_F2', 'TXD': 'TXD',
    'RESET': 'RESET', 'RG1': 'RG1', 'RG2': 'RG2', 'BLNK': 'BLNK', 'BLANC': 'BLANC', 'CM': 'C/~{M}',
    'COL1': 'COL1', 'COL2': 'COL2', 'COL3': 'COL3', 'FL1': 'FL1', 'FL2': 'FL2', 'FL3': 'FL3',
    'S1': 'S1', 'SR': 'SR', 'WE': 'WE', 'RAS': '~{RAS}', 'CAS1': '~{CAS1}', 'CAS2': '~{CAS2}', 'F3': 'F3', 'VR': 'VR', 'M12': '12M', 'M6': '6M',
    'MEMR': '~{MEMR}', 'IOR': '~{IOR}', 'IOW': '~{IOW}', 'INTA': '~{INTA}', 'INT': 'INT', 'DBIN': 'Net-(DD3-DBIN)', 'WR': 'Net-(DD3-~{WR})',
    'P1': 'Net-(DD66-D1)', 'P2': 'Net-(DD66-D2)', 'P3': 'Net-(DD66-D3)', 'BELL_C3': 'Net-(DD67-PC3)',
}
PROBE_BUS = {'A': [f'A{i}' for i in range(16)], 'D': [f'D{i}' for i in range(8)], 'BD': [f'BD{i}' for i in range(8)],
             'MA': [f'MA{i}' for i in range(9)], 'K': [f'K{i}' for i in range(1, 9)], 'C': [f'C{i}' for i in range(1, 6)],
             'PB17': ['32K', 'A16', 'A17', 'A18', '~{ENROM}', 'REST', 'ROMA13', 'ROMA14']}


def vname(n):
    return 'n_' + re.sub(r'[^A-Za-z0-9_]', '_', n.encode('ascii', 'backslashreplace').decode().replace('\\', 'u'))


def main():
    root = ET.parse(sys.argv[1]).getroot()
    report = '--report' in sys.argv
    comps = {}
    for c in root.iter('comp'):
        comps[c.get('ref')] = c.findtext('value')
    ptypes = {}
    for lp in root.iter('libpart'):
        for p in lp.iter('pin'):
            ptypes[(lp.get('part'), p.get('num'))] = p.get('type')
    partof = {}
    for c in root.iter('comp'):
        partof[c.get('ref')] = c.find('libsource').get('part')
    nets = {}
    pinnet = {}
    for n in root.iter('net'):
        name = n.get('name')
        nodes = [(nd.get('ref'), nd.get('pin'), nd.get('pintype') or ptypes.get((partof.get(nd.get('ref')), nd.get('pin')), '')) for nd in n.iter('node')]
        nets[name] = nodes
        for r, p, t in nodes:
            pinnet[(r, p)] = name
    names = {}
    taken = set()
    for n in sorted(nets):
        v = vname(n)
        while v in taken:
            v += '_'
        taken.add(v)
        names[n] = v
    over = {k: v for k, v in OVERRIDES}
    # names used in override expressions
    def expr(e):
        if e in ('osc', 'rst_btn', 'rxd'):
            return e
        cand = [k for k in nets if k == e or k.endswith('/' + e)]
        assert len(cand) == 1, (e, cand)
        return names[cand[0]]

    out = []
    out.append('// generated by gen_schem.py from the KiCad netlist of the Ocean-240.2 replica (romychs v1.0.3), do not edit')
    out.append('`timescale 1ns/100ps')
    out.append('module schem #(parameter ROM0 = "", ROM1 = "", PROM_VC = "") (input osc, input clk_cpu, input rst_btn, input rxd);')
    for n in sorted(nets):
        v = names[n]
        if n in ('GND', '/GND') or n.endswith('/GND'):
            out.append(f'\tsupply0 {v}; // {n}')
        elif n in ('VCC', '+5V') or n.endswith('/VCC'):
            out.append(f'\tsupply1 {v}; // {n}')
        else:
            out.append(f'\ttri1 {v}; // {n}')
    for n, e in OVERRIDES:
        cand = [k for k in nets if k == n]
        assert cand, n
        out.append(f'\tassign {names[n]} = {expr(e)};')
    def find(e):
        cand = [k for k in nets if k == e or k.endswith('/' + e)]
        return names[cand[0]] if len(cand) == 1 else None
    for k, e in PROBES.items():
        v = find(e)
        out.append(f'\twire pr_{k} = {v};' if v else f'\twire pr_{k} = 1\'bx; // {e}: no such net')
    for k, lst in PROBE_BUS.items():
        vs = [find(e) or "1'bx" for e in lst]
        out.append(f'\twire [{len(vs) - 1}:0] pr_{k} = {{{", ".join(reversed(vs))}}};')
    undriven = []
    used = set()
    for ref in sorted(comps, key=lambda s: (re.sub(r'\d', '', s), int(re.sub(r'\D', '', s) or 0))):
        val = comps[ref]
        mod = MODELS.get(val)
        if not mod:
            continue
        used.add(ref)
        conns = []
        for (r, p), n in sorted(pinnet.items(), key=lambda x: int(x[0][1]) if x[0][1].isdigit() else 0):
            if r != ref:
                continue
            t = ptypes.get((partof[ref], p), '')
            if t == 'power_in' or t == 'power_out':
                continue
            if (r, p) in CUT:
                conns.append(f'.p{p}()')
                continue
            conns.append(f'.p{p}({names[n]})')
        if mod == 'cpu8080':
            conns.append('.clk(clk_cpu)')
        par = PARAMS.get(ref)
        par = f' #({par})' if par else ''
        out.append(f'\t{mod}{par} u_{ref} ({", ".join(conns)});')
    out.append('endmodule')
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
    if report:
        for n, nodes in sorted(nets.items()):
            if n in over:
                continue
            digital = [(r, p, t) for r, p, t in nodes if r in used and (r, p) not in CUT]
            drivers = [x for x in digital if x[2] in DRIVER_TYPES]
            inputs = [x for x in digital if x[2] == 'input']
            if inputs and not drivers:
                others = [f'{r}.{p}' for r, p, t in nodes if r not in used]
                undriven.append((n, [f'{r}.{p}' for r, p, t in inputs], others))
        print('nets with inputs and no digital driver (read as 1 unless noted):')
        for n, i, o in undriven:
            print(f'  {n:40} in: {" ".join(i)[:90]}  | analog: {" ".join(o)[:80]}')


if __name__ == '__main__':
    main()
